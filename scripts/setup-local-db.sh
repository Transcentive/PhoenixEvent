#!/usr/bin/env bash
#
# Provision the local macOS development database for PhoenixEvent: one role and
# one database in the PostgreSQL 16 that Homebrew runs on port 5433, and
# backend/.env.
#
# Idempotent: safe to re-run. An existing role, database and .env are reused,
# so a re-run cannot rotate a password out from under a running server.
#
# Migrations are NOT applied here. The server applies them itself at startup.
set -euo pipefail

PGPORT="${PGPORT:-5433}"
PGHOST="${PGHOST:-localhost}"
PGBIN="${PGBIN:-/usr/local/opt/postgresql@16/bin}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$REPO_ROOT/backend/.env"
DB=phoenixevent
ROLE=phoenixevent

PSQL="$PGBIN/psql -h $PGHOST -p $PGPORT -d postgres -v ON_ERROR_STOP=1"

say() { printf '\n\033[1m%s\033[0m\n' "$1"; }

# --- preflight ---------------------------------------------------------------
if ! "$PGBIN/pg_isready" -h "$PGHOST" -p "$PGPORT" >/dev/null 2>&1; then
  echo "No PostgreSQL server answering on $PGHOST:$PGPORT." >&2
  echo "Start it with:  brew services start postgresql@16" >&2
  exit 1
fi

server_version="$($PSQL -Atc 'SHOW server_version;')"
say "PostgreSQL $server_version on $PGHOST:$PGPORT"
case "$server_version" in
  16.*) ;;
  *) echo "  ! The droplet runs PostgreSQL 16. This is $server_version." >&2 ;;
esac

# --- credentials -------------------------------------------------------------
DB_PASSWORD=""
if [ -f "$ENV_FILE" ]; then
  say "Reusing credentials from backend/.env"
  DB_PASSWORD="$(grep -oE "postgres://$ROLE:[^@]+@" "$ENV_FILE" | head -1 | sed "s|postgres://$ROLE:||; s|@||")"
fi
DB_PASSWORD="${DB_PASSWORD:-$(openssl rand -hex 16)}"

# --- role and database -------------------------------------------------------
say "Role"
if [ "$($PSQL -Atc "SELECT 1 FROM pg_roles WHERE rolname='$ROLE';")" = "1" ]; then
  $PSQL -qc "ALTER ROLE $ROLE WITH LOGIN PASSWORD '$DB_PASSWORD';"
  echo "  = $ROLE (existed, password re-applied)"
else
  $PSQL -qc "CREATE ROLE $ROLE WITH LOGIN PASSWORD '$DB_PASSWORD';"
  echo "  + $ROLE"
fi

say "Database"
if [ "$($PSQL -Atc "SELECT 1 FROM pg_database WHERE datname='$DB';")" = "1" ]; then
  echo "  = $DB (exists)"
else
  $PSQL -qc "CREATE DATABASE $DB OWNER $ROLE;"
  echo "  + $DB (owner: $ROLE)"
fi

# --- environment -------------------------------------------------------------
if [ -f "$ENV_FILE" ]; then
  say "backend/.env already exists, left as is"
else
  say "Writing backend/.env"
  cat > "$ENV_FILE" <<ENV
# Local development. Generated by scripts/setup-local-db.sh. Never committed.
# PostgreSQL 16 on $PGPORT; the system PostgreSQL 14 on 5432 is unrelated.

DATABASE_URL=postgres://$ROLE:$DB_PASSWORD@$PGHOST:$PGPORT/$DB?sslmode=disable
PORT=8082
STORAGE_PATH=$REPO_ROOT/.local/files

# Email. With SMTP_HOST empty, messages are written to the server log.
SMTP_HOST=
SMTP_PORT=587
SMTP_USERNAME=
SMTP_PASSWORD=
EMAIL_FROM=
ENV
  echo "  + $ENV_FILE"
fi

# Settings added after the file was first written are appended, and nothing
# already there is changed.
add_setting() {
  if ! grep -q "^$1=" "$ENV_FILE"; then
    printf '%s=%s\n' "$1" "$2" >> "$ENV_FILE"
    echo "  + $1"
  fi
}
if ! grep -q "^ORG_DOMAIN=" "$ENV_FILE"; then
  printf '\n# Addresses (spec 4A.5): each organization at <name>.phoenixevent.localhost:5174,\n# the general address at phoenixevent.localhost:5174.\n' >> "$ENV_FILE"
fi
add_setting ORG_DOMAIN phoenixevent.localhost
add_setting SITE_SCHEME http
add_setting SITE_PORT 5174
add_setting COOKIE_SECURE false
add_setting JWT_SECRET "$(openssl rand -hex 32)"
# The organization a phone on the same Wi-Fi reaches at the Mac's Wi-Fi
# address (scripts/run-local.sh). Empty: none.
add_setting LAN_ORGANIZATION ""

mkdir -p "$REPO_ROOT/.local/files" "$REPO_ROOT/.local/logs"

say "Done"
cat <<'NEXT'
  Start everything:

    ./scripts/run-local.sh        # then open http://phoenixevent.localhost:5174
NEXT
