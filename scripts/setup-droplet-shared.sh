#!/usr/bin/env bash
#
# Provision PhoenixEvent on the droplet that already serves The Mighty Queue
# (spec 2A.4). Run it ON the droplet, as root:
#
#   sudo ./setup-droplet-shared.sh
#
# It installs nothing and edits no existing configuration. It only ADDS: one
# PostgreSQL role, one database, a service user, directories, an environment
# file and the systemd unit. It never drops, alters or restarts anything that
# was already there.
#
# What it leaves to you, because each needs judgement about a live host: the
# DNS records, the nginx site for each address, and the certificates. See
# docs/installation.md.
#
# Idempotent. Re-running reuses the existing role, database and .env, so it
# cannot rotate a password out from under a running service.
set -euo pipefail

APP_ROOT=/srv/phoenixevent/app
DATA_ROOT=/srv/phoenixevent/data
SERVICE_USER=phoenixevent
DB=phoenixevent
ROLE=phoenixevent
PORT=8082
ENV_FILE="$APP_ROOT/backend/.env"

say() { printf '\n\033[1m== %s\033[0m\n' "$1"; }

[ "$(id -u)" = 0 ] || { echo "Run as root (sudo)." >&2; exit 1; }

say "Preflight"
command -v psql >/dev/null || { echo "PostgreSQL is not installed on this host." >&2; exit 1; }
PG_VERSION="$(sudo -u postgres psql -Atc 'SHOW server_version')"
echo "  PostgreSQL $PG_VERSION"
case "$PG_VERSION" in
  16.*) ;;
  *) echo "  ! The specification names PostgreSQL 16 (2A.2). This is $PG_VERSION." >&2 ;;
esac
if ss -ltn 2>/dev/null | grep -q ":$PORT "; then
  if ! systemctl is-active --quiet phoenixevent 2>/dev/null; then
    echo "Port $PORT is in use by something other than PhoenixEvent. Stopping." >&2
    exit 1
  fi
fi
echo "  port $PORT is free or already PhoenixEvent's"

PSQL="sudo -u postgres psql -v ON_ERROR_STOP=1 -Atc"

say "Credentials"
DB_PASSWORD=""
if [ -f "$ENV_FILE" ]; then
  DB_PASSWORD="$(grep -oE "postgres://$ROLE:[^@]+@" "$ENV_FILE" | head -1 | sed "s|postgres://$ROLE:||; s|@||")"
  echo "  reusing the password in $ENV_FILE"
fi
DB_PASSWORD="${DB_PASSWORD:-$(openssl rand -hex 24)}"

say "Role"
if [ "$($PSQL "SELECT 1 FROM pg_roles WHERE rolname='$ROLE'")" = "1" ]; then
  echo "  = $ROLE (exists)"
  # The password is re-applied only when .env holds it, so the two agree.
  [ -f "$ENV_FILE" ] && $PSQL "ALTER ROLE $ROLE WITH LOGIN PASSWORD '$DB_PASSWORD'" >/dev/null
else
  $PSQL "CREATE ROLE $ROLE WITH LOGIN PASSWORD '$DB_PASSWORD'" >/dev/null
  echo "  + $ROLE"
fi

say "Database"
if [ "$($PSQL "SELECT 1 FROM pg_database WHERE datname='$DB'")" = "1" ]; then
  echo "  = $DB (exists)"
else
  $PSQL "CREATE DATABASE $DB OWNER $ROLE" >/dev/null
  echo "  + $DB (owner: $ROLE)"
fi

say "Service user and directories"
if id "$SERVICE_USER" >/dev/null 2>&1; then
  echo "  = user $SERVICE_USER (exists)"
else
  useradd --system --home-dir /srv/phoenixevent --shell /usr/sbin/nologin "$SERVICE_USER"
  echo "  + user $SERVICE_USER"
fi
mkdir -p "$APP_ROOT/backend/migrations" "$APP_ROOT/frontend/dist" "$DATA_ROOT/files" /root/pe-backups
chown -R "$SERVICE_USER:$SERVICE_USER" /srv/phoenixevent
chmod 700 /root/pe-backups
echo "  $APP_ROOT, $DATA_ROOT/files, /root/pe-backups"

say "Environment"
if [ -f "$ENV_FILE" ]; then
  echo "  = $ENV_FILE (exists, left as is)"
else
  cat > "$ENV_FILE" <<ENV
# PhoenixEvent on the test droplet. Generated by setup-droplet-shared.sh.
DATABASE_URL=postgres://$ROLE:$DB_PASSWORD@localhost:5432/$DB?sslmode=disable
PORT=$PORT
STORAGE_PATH=$DATA_ROOT/files

# Email through Rackspace (spec 2A.2). Fill these in from the Rackspace
# account; with SMTP_HOST empty, messages are written to the service's log.
SMTP_HOST=
SMTP_PORT=587
SMTP_USERNAME=
SMTP_PASSWORD=
EMAIL_FROM=
ENV
  chown "$SERVICE_USER:$SERVICE_USER" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  echo "  + $ENV_FILE (readable by $SERVICE_USER only)"
fi

say "systemd unit"
if [ -f "$(dirname "$0")/phoenixevent.service" ]; then
  install -m 0644 "$(dirname "$0")/phoenixevent.service" /etc/systemd/system/phoenixevent.service
  systemctl daemon-reload
  systemctl enable phoenixevent >/dev/null 2>&1
  echo "  installed and enabled; the first deploy starts it"
else
  echo "  ! phoenixevent.service is not beside this script; copy it over and run this again"
fi

say "Done"
echo "  Next: from the Mac, ./scripts/deploy.sh root@droplet"
